// Bundles the /capture browser script (src/client/capture.ts and its imports) into one classic-script IIFE, and
// writes it as a TypeScript string constant to src/generated/capture-script.ts. That directory is gitignored.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'src/client/capture.ts');
const output = resolve(root, 'src/generated/capture-script.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  platform: 'browser',
  minify: false,
  legalComments: 'none',
  write: false,
});
const [bundle] = result.outputFiles;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, [
  '// Generated by scripts/build-client.mjs from src/client/capture.ts. Do not edit; run `npm run build:client`.',
  `export const captureScript = ${JSON.stringify(bundle.text)};`,
  '',
].join('\n'));
