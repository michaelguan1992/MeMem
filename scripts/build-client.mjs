// Bundles the /capture browser script (src/client/capture.ts and its imports) into one classic-script IIFE, and
// writes it as a TypeScript string constant to src/generated/capture-script.ts. That directory is gitignored.
//
// The e2e run maps browser coverage back to the TypeScript, so it needs the same bundle with an inline source map.
// `--bundle-out <file> --sourcemap` writes that bundle as plain JavaScript. The module is never written with a map.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'src/client/capture.ts');
const output = resolve(root, 'src/generated/capture-script.ts');

/** The bundle's JavaScript. With `sourcemap`, it ends with an inline source map. */
export async function bundleCaptureScript({ sourcemap = false } = {}) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    minify: false,
    legalComments: 'none',
    write: false,
    sourcemap: sourcemap ? 'inline' : false,
  });
  const [bundle] = result.outputFiles;
  return bundle.text;
}

async function main(args) {
  const flag = args.indexOf('--bundle-out');
  const bundleOut = flag === -1 ? undefined : args[flag + 1];
  if (flag !== -1 && !bundleOut) throw new Error('--bundle-out needs a file path.');
  const sourcemap = args.includes('--sourcemap');
  if (sourcemap && bundleOut === undefined) throw new Error('--sourcemap needs --bundle-out; the served module never has a source map.');

  const bundle = await bundleCaptureScript({ sourcemap });
  if (bundleOut !== undefined) {
    await mkdir(dirname(resolve(bundleOut)), { recursive: true });
    await writeFile(resolve(bundleOut), bundle);
    return;
  }
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, [
    '// Generated by scripts/build-client.mjs from src/client/capture.ts. Do not edit; run `npm run build:client`.',
    `export const captureScript = ${JSON.stringify(bundle)};`,
    '',
  ].join('\n'));
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main(process.argv.slice(2));
}
