// Bundles the browser scripts into one classic-script IIFE each, and writes each as a TypeScript string constant:
// src/generated/capture-script.ts (the /capture page, from src/client/capture.ts) and src/generated/history-script.ts (the
// /capture/history page, from src/client/history.ts). That directory is gitignored.
//
// The bundle is built from the directory the command runs in, not from this file's own location. A mutator worker is a
// symlink overlay: its src/client/capture.ts is the mutated copy, and this file is a link into the real tree, so a root
// taken from this file would bundle the unmutated tree. The generated module is never written through a link, because
// a link leads into another tree.
//
// The e2e run maps browser coverage back to the TypeScript, so it needs the /capture bundle with an inline source map.
// `--bundle-out <file> --sourcemap` writes that bundle as plain JavaScript. The module is never written with a map.
import { realpathSync } from 'node:fs';
import { lstat, mkdir, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

/** The bundle's JavaScript for the entry file at `entry` in the tree at `root`. With `sourcemap`, it ends with an inline source map. */
export async function bundleClientScript(entry, { root = process.cwd(), sourcemap = false } = {}) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [resolve(root, entry)],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    minify: false,
    legalComments: 'none',
    write: false,
    sourcemap: sourcemap ? 'inline' : false,
  });
  const [bundle] = result.outputFiles;
  return bundle.text;
}

/** The /capture bundle for the tree at `root`. */
export async function bundleCaptureScript({ root = process.cwd(), sourcemap = false } = {}) {
  return bundleClientScript('src/client/capture.ts', { root, sourcemap });
}

/** The /capture/history bundle for the tree at `root`. It has no coverage harness, so it never carries a source map. */
export async function bundleHistoryScript({ root = process.cwd() } = {}) {
  return bundleClientScript('src/client/history.ts', { root });
}

// Each generated module holds one bundle under the name the server imports it by.
const GENERATED = [
  { file: 'capture-script.ts', name: 'captureScript', entry: 'src/client/capture.ts', bundle: bundleCaptureScript },
  { file: 'history-script.ts', name: 'historyScript', entry: 'src/client/history.ts', bundle: bundleHistoryScript },
];

async function main(args) {
  const root = process.cwd();
  const flag = args.indexOf('--bundle-out');
  const bundleOut = flag === -1 ? undefined : args[flag + 1];
  if (flag !== -1 && !bundleOut) throw new Error('--bundle-out needs a file path.');
  const sourcemap = args.includes('--sourcemap');
  if (sourcemap && bundleOut === undefined) throw new Error('--sourcemap needs --bundle-out; the served module never has a source map.');

  if (bundleOut !== undefined) {
    const bundle = await bundleCaptureScript({ root, sourcemap });
    await mkdir(dirname(resolve(bundleOut)), { recursive: true });
    await writeFile(resolve(bundleOut), bundle);
    return;
  }
  const generatedDir = resolve(root, 'src/generated');
  if ((await lstat(generatedDir).catch(() => null))?.isSymbolicLink()) {
    throw new Error('src/generated is a link into another tree, so this build does not write it. Run npm run build:client in that tree.');
  }
  await mkdir(generatedDir, { recursive: true });
  for (const module of GENERATED) {
    await writeGenerated(generatedDir, module, await module.bundle({ root }));
  }
}

// Written beside the target and renamed into place, so a test that reads the module never sees a partial file.
async function writeGenerated(generatedDir, { file, name, entry }, bundle) {
  const target = resolve(generatedDir, file);
  const staging = `${target}.${process.pid}.tmp`;
  await writeFile(staging, [
    `// Generated by scripts/build-client.mjs from ${entry}. Do not edit; run \`npm run build:client\`.`,
    `export const ${name} = ${JSON.stringify(bundle)};`,
    '',
  ].join('\n'));
  await rename(staging, target);
}

// Runs main only when this file is the entry point. Both paths are compared as real paths: a mutator worker reaches this
// file through a link, and Node reports the real path in import.meta.url.
if (process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  await main(process.argv.slice(2));
}
